#!/usr/bin/env node
// Create demo testnet accounts, deploy the contract, and register payees.
// Keys are written to .env.local and are not committed.
//
//   npm run seed

import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { Account, JsonRpcProvider, KeyPair, nearToYocto, teraToGas } from "near-api-js";
import demo from "../config/demo-payees.json" with { type: "json" };

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const RPC = process.env.NEAR_RPC_URL || "https://test.rpc.fastnear.com";
const PARENT = process.env.CONTRACT_ACCOUNT_ID || "plock5dfa73.testnet";
const CRED = path.join(process.env.HOME || "", ".near-credentials", "testnet", `${PARENT}.json`);
const WASM = path.join(ROOT, "contract/target/wasm32-unknown-unknown/release/payee_lock.wasm");
const ENV_PATH = path.join(ROOT, ".env.local");
const DEPLOYED_PATH = path.join(ROOT, "config/deployed.json");
const MIN_DELAY = 60;
const YOCTO = 10n ** 24n;

function run(command, args) {
  const result = spawnSync(command, args, { stdio: "inherit", cwd: ROOT });
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} failed`);
  }
}

function loadEnv(file) {
  if (!fs.existsSync(file)) return {};
  const values = {};
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (match) values[match[1]] = match[2];
  }
  return values;
}

function writeEnv(values) {
  const lines = [
    "# Generated by npm run seed. Do not commit.",
    `NEAR_NETWORK_ID=testnet`,
    `NEAR_RPC_URL=${RPC}`,
    `CONTRACT_ID=${PARENT}`,
    `GUARDIAN_ACCOUNT_ID=${values.guardian.accountId}`,
    `GUARDIAN_PRIVATE_KEY=${values.guardian.privateKey}`,
  ];
  for (const payee of demo.payees) {
    const record = values[payee.slug];
    const name = payee.slug.toUpperCase();
    lines.push(`${name}_ACCOUNT_ID=${record.accountId}`);
    lines.push(`${name}_PRIVATE_KEY=${record.privateKey}`);
  }
  lines.push("");
  fs.writeFileSync(ENV_PATH, lines.join("\n"));
}

function ensureParentKey() {
  if (!fs.existsSync(CRED)) {
    console.log(`Creating ${PARENT} via the testnet faucet...`);
    run("near", [
      "account",
      "create-account",
      "sponsor-by-faucet-service",
      PARENT,
      "autogenerate-new-keypair",
      "save-to-keychain",
      "network-config",
      "testnet",
      "create",
    ]);
  }
  if (!fs.existsSync(CRED)) {
    throw new Error(
      `${PARENT} has no local key at ${CRED}. Set CONTRACT_ACCOUNT_ID to a fresh name and run npm run seed again.`,
    );
  }
  const saved = JSON.parse(fs.readFileSync(CRED, "utf8"));
  if (!saved.private_key) throw new Error(`No private_key in ${CRED}`);
  return saved.private_key;
}

function ensureWasm() {
  if (!fs.existsSync(WASM)) {
    console.log("Building the contract wasm...");
    run("cargo", [
      "build",
      "--manifest-path",
      "contract/Cargo.toml",
      "--release",
      "--target",
      "wasm32-unknown-unknown",
    ]);
  }
  if (!fs.existsSync(WASM)) throw new Error(`Missing wasm at ${WASM}`);
}

async function accountExists(provider, accountId) {
  try {
    await provider.viewAccount({ accountId });
    return true;
  } catch {
    return false;
  }
}

async function liquidYocto(provider, accountId) {
  const info = await provider.viewAccount({ accountId });
  const locked = BigInt(info.storage_usage) * 10n ** 19n;
  const liquid = info.amount - locked;
  return liquid > 0n ? liquid : 0n;
}

const provider = new JsonRpcProvider({ url: RPC });
const parentKey = ensureParentKey();
ensureWasm();
const parent = new Account(PARENT, provider, parentKey);

let initialized = false;
try {
  await provider.callFunction({ contractId: PARENT, method: "get_config", args: {} });
  initialized = true;
} catch {
  initialized = false;
}

console.log(initialized ? "Updating contract code..." : "Deploying and initializing...");
await parent.deployContract(new Uint8Array(fs.readFileSync(WASM)));
if (!initialized) {
  await parent.callFunction({
    contractId: PARENT,
    methodName: "init",
    args: { min_delay_seconds: MIN_DELAY },
    gas: teraToGas("80"),
  });
}

const existingEnv = loadEnv(ENV_PATH);
const slugs = ["guardian", ...demo.payees.map((payee) => payee.slug)];
const missing = [];
for (const slug of slugs) {
  const accountId = `${slug}.${PARENT}`;
  if (!(await accountExists(provider, accountId))) missing.push(slug);
}

if (missing.length > 0) {
  const liquid = await liquidYocto(provider, PARENT);
  const reserve = nearToYocto("0.4");
  const spendable = liquid > reserve ? liquid - reserve : 0n;
  const share = spendable / BigInt(missing.length);
  const cap = nearToYocto("1");
  const transfer = share > cap ? cap : share;
  if (transfer < nearToYocto("0.15")) {
    const near = Number(liquid) / Number(YOCTO);
    throw new Error(
      `${PARENT} has about ${near.toFixed(3)} liquid NEAR, not enough to fund ${missing.join(", ")}.`,
    );
  }
  console.log(`Funding ${missing.length} new account(s) with ${Number(transfer) / Number(YOCTO)} NEAR each...`);
  for (const slug of missing) {
    const key = KeyPair.fromRandom("ed25519");
    await parent.createSubAccount({
      accountOrPrefix: slug,
      publicKey: key.getPublicKey().toString(),
      nearToTransfer: transfer,
    });
    existingEnv[`${slug.toUpperCase()}_ACCOUNT_ID`] = `${slug}.${PARENT}`;
    existingEnv[`${slug.toUpperCase()}_PRIVATE_KEY`] = key.toString();
    console.log(`Created ${slug}.${PARENT}`);
  }
}

const records = {};
for (const slug of slugs) {
  const name = slug.toUpperCase();
  const accountId = existingEnv[`${name}_ACCOUNT_ID`] || `${slug}.${PARENT}`;
  const privateKey = existingEnv[`${name}_PRIVATE_KEY`];
  if (!privateKey) {
    throw new Error(`${accountId} already exists but ${name}_PRIVATE_KEY is missing from .env.local`);
  }
  records[slug] = { accountId, privateKey };
}

const guardianId = records.guardian.accountId;
for (const spec of demo.payees) {
  const record = records[spec.slug];
  const current = await provider.callFunction({
    contractId: PARENT,
    method: "get_payee",
    args: { payee: record.accountId },
  });
  if (current) {
    console.log(`${record.accountId} is already registered`);
    continue;
  }
  const addresses = [
    { chain: "near", address: record.accountId },
    ...Object.entries(spec.addresses).map(([chain, address]) => ({ chain, address })),
  ];
  const account = new Account(record.accountId, provider, record.privateKey);
  console.log(`Registering ${spec.displayName}...`);
  await account.callFunction({
    contractId: PARENT,
    methodName: "register",
    args: {
      display_name: spec.displayName,
      guardian: guardianId,
      delay_seconds: demo.delaySeconds,
      addresses,
    },
    gas: teraToGas("100"),
    deposit: nearToYocto("0.02"),
  });
}

writeEnv(records);
const deployed = {
  networkId: "testnet",
  rpcUrl: RPC,
  contractId: PARENT,
  minDelaySeconds: MIN_DELAY,
  recommendedDelaySeconds: 72 * 60 * 60,
  demoDelaySeconds: demo.delaySeconds,
  guardianAccountId: guardianId,
  explorerAccount: "https://testnet.nearblocks.io/address",
  payees: demo.payees.map((spec) => ({
    slug: spec.slug,
    accountId: records[spec.slug].accountId,
    displayName: spec.displayName,
    delaySeconds: demo.delaySeconds,
    guardianAccountId: guardianId,
    addresses: {
      near: records[spec.slug].accountId,
      ...spec.addresses,
    },
    ...(spec.poison ? { poison: spec.poison } : {}),
  })),
};
fs.writeFileSync(DEPLOYED_PATH, `${JSON.stringify(deployed, null, 2)}\n`);
console.log(`\nContract: ${PARENT}`);
console.log(`Keys written to ${ENV_PATH} (not committed).`);
console.log("Restart npm run dev so Next.js picks up .env.local.");
